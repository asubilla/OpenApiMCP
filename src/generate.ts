import { mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";

export interface GenerateSpec {
  /** Path (relative to the output dir) of the bundled spec file. */
  file: string;
  /** Dereferenced document to write. */
  doc: any;
}

export interface GenerateInput {
  out: string;
  name: string;
  version: string;
  specs: GenerateSpec[];
  config: {
    baseUrl?: string;
    headers: Record<string, string>;
    fields?: string[];
    timeoutMs: number;
    maxBytes: number;
    retries: number;
    cacheTtlMs: number;
    paginate: boolean;
    maxPages: number;
  };
}

/** Write a standalone, publishable MCP server project that bundles the spec(s). */
export function generateProject(input: GenerateInput): string[] {
  const { out } = input;
  const files: string[] = [];

  const write = (rel: string, content: string) => {
    const target = path.join(out, rel);
    mkdirSync(path.dirname(target), { recursive: true });
    writeFileSync(target, content);
    files.push(rel);
  };

  for (const spec of input.specs) write(spec.file, JSON.stringify(spec.doc, null, 2) + "\n");

  const config = { name: input.name, version: input.version, specs: input.specs.map((s) => s.file), ...input.config };
  write("openapimcp.config.json", JSON.stringify(config, null, 2) + "\n");

  write(
    "package.json",
    JSON.stringify(
      {
        name: input.name,
        version: "0.1.0",
        private: true,
        type: "module",
        scripts: { start: "node --import tsx src/index.ts" },
        dependencies: { "@asubilla/openapimcp": `^${input.version}` },
        devDependencies: { tsx: "^4.23.15" }
      },
      null,
      2
    ) + "\n"
  );

  write(
    "tsconfig.json",
    JSON.stringify(
      {
        compilerOptions: {
          target: "ES2022",
          module: "NodeNext",
          moduleResolution: "NodeNext",
          strict: true,
          skipLibCheck: true
        },
        include: ["src/**/*.ts"]
      },
      null,
      2
    ) + "\n"
  );

  write("src/index.ts", generatedIndex());
  write(".gitignore", "node_modules/\n");
  write("Dockerfile", generatedDockerfile());
  write("README.md", generatedReadme(input.name, config.specs.length));

  return files;
}

function generatedIndex(): string {
  return `import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { parseDocument, buildServer, serveStdio } from "@asubilla/openapimcp";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const config = JSON.parse(readFileSync(path.join(root, "openapimcp.config.json"), "utf8"));

const slugify = (value: string) =>
  value.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "") || "api";

const apis = config.specs.map((rel: string) =>
  parseDocument(JSON.parse(readFileSync(path.join(root, rel), "utf8")))
);
const multi = apis.length > 1;
const tools = apis.flatMap((api: any) =>
  api.tools.map((tool: any) => (multi ? { ...tool, name: \`\${slugify(api.title)}_\${tool.name}\` } : tool))
);

serveStdio(() =>
  buildServer(
    { ...apis[0], tools },
    {
      serverName: config.name,
      version: config.version,
      baseUrl: config.baseUrl || undefined,
      headers: config.headers ?? {},
      timeoutMs: config.timeoutMs,
      maxBytes: config.maxBytes,
      fields: Array.isArray(config.fields) && config.fields.length ? config.fields : undefined,
      retries: config.retries,
      cacheTtlMs: config.cacheTtlMs,
      paginate: config.paginate,
      maxPages: config.maxPages
    }
  )
);

console.error(\`\${config.name} MCP server running on stdio (\${tools.length} tools)\`);
`;
}

function generatedDockerfile(): string {
  return `FROM node:20-alpine
WORKDIR /app
COPY package.json ./
RUN npm install --omit=optional
COPY . .
CMD ["npm", "start"]
`;
}

function generatedReadme(name: string, specCount: number): string {
  return `# ${name}

A standalone MCP server generated by [openapimcp](https://www.npmjs.com/package/@asubilla/openapimcp).

It bundles ${specCount} OpenAPI spec(s), so it runs offline with no spec URL.

## Run

\`\`\`bash
npm install
npm start
\`\`\`

Then wire it into your agent as a local (stdio) MCP server:

\`\`\`json
{
  "mcp": {
    "servers": {
      "${name}": { "type": "local", "command": ["node", "dist/index.js"] }
    }
  }
}
\`\`\`

Set credentials via \`OPENAPIMCP_<SCHEME>\` environment variables. Edit
\`openapimcp.config.json\` to change the base URL, headers, timeouts, retries,
caching, or pagination.
`;
}
